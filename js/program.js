let n = 0;
function day(partial) {
  const verse = VERSES[n];
  const item = {
    index: n,
    id: `w${partial.week}d${partial.day}`,
    calming: CALM_CYCLE[n % CALM_CYCLE.length],
    verse: { ref: verse[0], text: verse[1] },
    starters: { tabby: T_START, brandon: B_START },
    privateUntilFinished: partial.owner !== "both",
    ...partial,
  };
  n += 1;
  return item;
}

